"""
Consolidated Final Progress Report Generator

This script:
1. Checks that weekly reports exist.
2. Verifies that 9 weekly reports are available.
3. Runs the existing report generator in final mode.
4. Generates a consolidated report using complete Git history.

Requirements:
    pip install reportlab matplotlib
"""

import os
import sys
import subprocess
from pathlib import Path


# --------------------------------------------------
# CONFIGURATION
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent

WEEKLY_REPORT_DIR = BASE_DIR / "weekly_reports"
FINAL_REPORT_DIR = BASE_DIR / "final_reports"

EXPECTED_REPORTS = 9

REPORT_SCRIPT = BASE_DIR / "generate_report.py"


# --------------------------------------------------
# CHECK WEEKLY REPORTS
# --------------------------------------------------

def check_weekly_reports():

    print("\nChecking weekly reports...")

    if not WEEKLY_REPORT_DIR.exists():
        raise FileNotFoundError(
            "weekly_reports directory does not exist."
        )

    reports = list(
        WEEKLY_REPORT_DIR.glob(
            "*_Weekly_Progress_Report_Form-3_*.pdf"
        )
    )

    reports.sort()

    print(f"Weekly reports found: {len(reports)}")

    for report in reports:
        print(f" - {report.name}")

    if len(reports) < EXPECTED_REPORTS:
        raise ValueError(
            f"Expected {EXPECTED_REPORTS} weekly reports, "
            f"but found only {len(reports)}."
        )

    print("\nAll required weekly reports are available.")

    return reports


# --------------------------------------------------
# GENERATE CONSOLIDATED REPORT
# --------------------------------------------------

def generate_final_report():

    print("\nGenerating consolidated final report...")

    if not REPORT_SCRIPT.exists():
        raise FileNotFoundError(
            "generate_report.py was not found."
        )

    FINAL_REPORT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    # Run the existing report generator in final mode.
    # This uses the complete Git history and preserves
    # the existing PDF format.

    subprocess.run(
        [
            sys.executable,
            str(REPORT_SCRIPT),
            "final"
        ],
        cwd=BASE_DIR,
        check=True
    )

    print("\nFinal report generation completed.")


# --------------------------------------------------
# MOVE GENERATED FINAL REPORT
# --------------------------------------------------

def archive_final_report():

    print("\nSearching for generated final PDF...")

    generated_reports = list(
        BASE_DIR.glob(
            "*_Final_Progress_Report_Form-3_*.pdf"
        )
    )

    if not generated_reports:
        raise FileNotFoundError(
            "No final progress report PDF was generated. "
            "Check the filename generated by generate_report.py."
        )

    generated_reports.sort(
        key=lambda file: file.stat().st_mtime,
        reverse=True
    )

    latest_report = generated_reports[0]

    destination = FINAL_REPORT_DIR / latest_report.name

    # Avoid moving a file onto itself.
    if latest_report.resolve() != destination.resolve():
        if destination.exists():
            destination.unlink()

        latest_report.replace(destination)

    print("\nFinal report archived successfully.")
    print(f"Location: {destination}")

    return destination


# --------------------------------------------------
# MAIN FUNCTION
# --------------------------------------------------

def main():

    print("=" * 60)
    print("CONSOLIDATED FINAL PROGRESS REPORT")
    print("=" * 60)

    try:

        # Step 1: Validate weekly reports.
        check_weekly_reports()

        # Step 2: Generate cumulative report.
        generate_final_report()

        # Step 3: Archive generated PDF.
        archive_final_report()

        print("\n" + "=" * 60)
        print("FINAL REPORT GENERATED SUCCESSFULLY")
        print("=" * 60)

    except Exception as error:

        print("\nERROR:", str(error))
        sys.exit(1)


if __name__ == "__main__":
    main()
